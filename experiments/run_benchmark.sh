#!/bin/bash -l
#SBATCH --time=72:00:00
#SBATCH --partition=small
#SBATCH --job-name=masked14_fpa10_5000_train
#SBATCH --error=err_%x_%A_%a.txt
#SBATCH --output=out_%x_%A_%a.txt
#SBATCH --ntasks=1
#SBATCH --cpus-per-task=4
#SBATCH --mem=512G
#SBATCH --gres=gpu:1
#SBATCH --array=0-9%10

set -euo pipefail

export PYTHONNOUSERSITE=1
unset PYTHONPATH
export CUDA_VISIBLE_DEVICES=0
export PYTHONUNBUFFERED=1

source "$HOME/miniconda3/etc/profile.d/conda.sh"
conda activate hidden-cascades

PYTHON="$HOME/miniconda3/envs/hidden-cascades/bin/python"

PROJECT_DIR="${SAGE_HC_ROOT:-${SLURM_SUBMIT_DIR:-$PWD}}"
TRAIN_SCRIPT="$PROJECT_DIR/core/train_benchmark.py"
GRAPH_FOLDER="$PROJECT_DIR/data/graphs"

FEATURES_ROOT="/scratch/svc_td_fincomp/vrango/hic_new/assignment_split/features"
LOG_DIR="$PROJECT_DIR/main_results"
STATUS_DIR="$LOG_DIR/completion_status_v2_cascades"
LOCK_DIR="$LOG_DIR/locks_v2_cascades"
UNCERTAINTY_RESULTS_DIR="$LOG_DIR/results_assignment_masked14_dual_fpa_uncertainty"
TEST_MANIFEST_DIR="$PROJECT_DIR/main_results_test_data"

SUBSET_SEED=0
SPLIT_SEED=0

# Every node acts as a seed. These values must match simulation.
SEED_PERCENTAGE="1.0"
SEED_TAG="seed100"

# Data generated by simulate_data_parallel_hic_self_seed_partial.py.
FEATURE_MODE="multiple_new_features_self_seed_masked"
FEATURE_TAG="self_seed_masked_14features_v1"
AVAILABLE_FEATURE_DIMENSION=14

# Number of feature columns supplied to the model.
# Use 14 for all stored columns, or change to 9 for the original first 9 columns.
INPUT_FEATURE_COUNT=14

NUM_CASCADES=50
ALPHA="0.8"

# Training settings
MODEL_NAME="rggcn"
K_RUNS=5
NUM_EPOCHS=100
LEARNING_RATE="0.001"
WEIGHT_DECAY="0.0001"
PATIENCE=20
MIN_EPOCHS=100
BATCH_SIZE=8

# The uncertainty summary is printed in every log.
COMPUTE_UNCERTAINTY="True"
UNCERTAINTY_CONFIDENCE="1.96"

# Detailed assignment-level JSON can become very large for the 10,000-assignment
# experiments. Keep this False unless those files are specifically required.
SAVE_UNCERTAINTY_RESULTS="False"

# Save the exact combined test sample IDs for each subset. The manifest points
# to the reusable master cascade shards; it does not duplicate cascade arrays.
SAVE_TEST_MANIFEST="True"
VERIFY_CASCADE_SHARDS="False"

# Run only the FPA10 dataset and only the 5,000-assignment subset.
VALUE=5000
MASTER_ASSIGNMENTS=10000
FEATURES_PER_ASSIGNMENT=10
DATASET_INDEX=0
DATASET_TAG="fpa10_master10000"

GRAPH_LABELS=(tree karate ba2 ba3 ba4)
GRAPH_NAMES=(tree karate random random random)
NODE_COUNTS=(5 34 100 100 100)
CONNECTIONS_PER_NODE=(2 2 2 3 4)

NUM_GRAPHS=${#GRAPH_LABELS[@]}
NUM_NOISE_SETTINGS=2
EXPECTED_TASKS=$((NUM_GRAPHS * NUM_NOISE_SETTINGS))

if (( SLURM_ARRAY_TASK_ID < 0 || SLURM_ARRAY_TASK_ID >= EXPECTED_TASKS )); then
    echo "Invalid array task ID: $SLURM_ARRAY_TASK_ID" >&2
    echo "Expected an ID from 0 to $((EXPECTED_TASKS - 1))." >&2
    exit 2
fi

# Array layout (10 tasks total):
#   0-1 -> tree,   nop / p020_q060
#   2-3 -> karate, nop / p020_q060
#   4-5 -> ba2,    nop / p020_q060
#   6-7 -> ba3,    nop / p020_q060
#   8-9 -> ba4,    nop / p020_q060
GRAPH_INDEX=$((SLURM_ARRAY_TASK_ID / NUM_NOISE_SETTINGS))
P_INDEX=$((SLURM_ARRAY_TASK_ID % NUM_NOISE_SETTINGS))

GRAPH_LABEL=${GRAPH_LABELS[$GRAPH_INDEX]}
GRAPH_NAME=${GRAPH_NAMES[$GRAPH_INDEX]}
NODE_COUNT=${NODE_COUNTS[$GRAPH_INDEX]}
CPN=${CONNECTIONS_PER_NODE[$GRAPH_INDEX]}

if [ "$P_INDEX" -eq 0 ]; then
    P_SETTING="nop"
    P1="0.0"
    P2="0.0"
    Q_VAL="1.0"
else
    P_SETTING="p020_q060"
    P1="0.2"
    P2="0.2"
    Q_VAL="0.6"
fi

EXP_NAME="sens_${GRAPH_LABEL}_assignments_${VALUE}_${P_SETTING}_${SEED_TAG}_masked14_cascadesv1_${DATASET_TAG}_input${INPUT_FEATURE_COUNT}_nested_norm_uncertainty"
FEATURES_FOLDER="$FEATURES_ROOT/$SEED_TAG/$GRAPH_LABEL/$P_SETTING/$FEATURE_TAG"
LOG_FILE="$LOG_DIR/${EXP_NAME}.log"

P1_TAG=${P1//./}
P2_TAG=${P2//./}
MASTER_FILE="$FEATURES_FOLDER/features_graph_${GRAPH_NAME}_agt_${FEATURE_MODE}_nc${NODE_COUNT}_cpn${CPN}_na${MASTER_ASSIGNMENTS}_nc${NUM_CASCADES}_a${ALPHA}_p${P1_TAG}_${P2_TAG}_q${Q_VAL}_fpa${FEATURES_PER_ASSIGNMENT}.pkl"
MASTER_SHARD_DIR="${MASTER_FILE%.pkl}"
DATASET_STEM=$(basename "${MASTER_FILE%.pkl}")
DATASET_STEM=${DATASET_STEM#features_}
CASCADE_SHARD_DIR="$FEATURES_FOLDER/cascades_${DATASET_STEM}"
TEST_MANIFEST_FILE="$TEST_MANIFEST_DIR/${EXP_NAME}_test_manifest.json"

RUN_TAG="${MODEL_NAME}_k${K_RUNS}_ep${NUM_EPOCHS}_lr${LEARNING_RATE}_wd${WEIGHT_DECAY}_pat${PATIENCE}_min${MIN_EPOCHS}_subset${SUBSET_SEED}_split${SPLIT_SEED}_input${INPUT_FEATURE_COUNT}_unc${COMPUTE_UNCERTAINTY}"
RUN_TAG=${RUN_TAG//./p}

DONE_FILE="$STATUS_DIR/${EXP_NAME}_${RUN_TAG}.done"
LOCK_FILE="$LOCK_DIR/${EXP_NAME}_${RUN_TAG}.lock"
RUN_HEADER="========== MASKED14 FPA10 5000-ASSIGNMENT TRAINING =========="

mkdir -p "$LOG_DIR" "$STATUS_DIR" "$LOCK_DIR" "$TEST_MANIFEST_DIR"
if [ "$SAVE_UNCERTAINTY_RESULTS" = "True" ]; then
    mkdir -p "$UNCERTAINTY_RESULTS_DIR"
fi

# Start the per-experiment log before skip, lock, and preflight checks so every
# exit reason is visible in the same log file.
exec > >(tee -a "$LOG_FILE") 2>&1

echo "Launcher entered at $(date -Is)"
echo "SLURM job ID: ${SLURM_JOB_ID:-unknown}; array task: ${SLURM_ARRAY_TASK_ID:-unknown}"

# Return success only when the latest attempt in this experiment log reached
# its Finished line. An older successful attempt followed by a newer failed
# attempt is therefore not treated as complete.
latest_log_run_completed() {
    [ -f "$LOG_FILE" ] || return 1

    awk -v header="$RUN_HEADER" -v experiment="$EXP_NAME" '
        $0 == header {
            latest_block = ""
            found_block = 1
        }
        found_block {
            latest_block = latest_block $0 ORS
        }
        END {
            if (!found_block) {
                exit 1
            }

            finished_spaced = "Finished:    " experiment
            finished_plain = "Finished: " experiment

            if (index(latest_block, finished_spaced) > 0 ||
                index(latest_block, finished_plain) > 0) {
                exit 0
            }

            exit 1
        }
    ' "$LOG_FILE"
}

write_done_marker() {
    local source="$1"
    local temp_done="${DONE_FILE}.tmp.$$"

    {
        echo "marker_version=2_cascades"
        echo "experiment=$EXP_NAME"
        echo "status=completed"
        echo "completion_source=$source"
        echo "completed_at=$(date -Is)"
        echo "slurm_job_id=${SLURM_JOB_ID:-unknown}"
        echo "slurm_array_task_id=${SLURM_ARRAY_TASK_ID:-unknown}"
        echo "dataset_tag=$DATASET_TAG"
        echo "graph=$GRAPH_LABEL"
        echo "noise_setting=$P_SETTING"
        echo "selected_assignments=$VALUE"
        echo "source_assignments=$MASTER_ASSIGNMENTS"
        echo "features_per_assignment=$FEATURES_PER_ASSIGNMENT"
        echo "feature_mode=$FEATURE_MODE"
        echo "available_feature_dimension=$AVAILABLE_FEATURE_DIMENSION"
        echo "input_feature_count=$INPUT_FEATURE_COUNT"
        echo "model=$MODEL_NAME"
        echo "k_runs=$K_RUNS"
        echo "num_epochs=$NUM_EPOCHS"
        echo "learning_rate=$LEARNING_RATE"
        echo "weight_decay=$WEIGHT_DECAY"
        echo "patience=$PATIENCE"
        echo "min_epochs=$MIN_EPOCHS"
        echo "subset_seed=$SUBSET_SEED"
        echo "split_seed=$SPLIT_SEED"
        echo "compute_uncertainty=$COMPUTE_UNCERTAINTY"
        echo "uncertainty_confidence=$UNCERTAINTY_CONFIDENCE"
        echo "save_test_manifest=$SAVE_TEST_MANIFEST"
        echo "test_manifest_file=$TEST_MANIFEST_FILE"
        echo "cascade_shard_directory=$CASCADE_SHARD_DIR"
        echo "log_file=$LOG_FILE"
    } > "$temp_done"

    mv "$temp_done" "$DONE_FILE"
}

# Skip settings completed under this marker system.
if [ -f "$DONE_FILE" ]; then
    echo "SKIPPED: experiment already completed."
    echo "Experiment:  $EXP_NAME"
    echo "Done marker: $DONE_FILE"
    exit 0
fi

# Recover completion state if the launcher finished previously but its marker
# was removed. Only the latest log block is inspected.
if latest_log_run_completed; then
    write_done_marker "latest_completed_log_block"
    echo "SKIPPED: latest existing log block completed successfully."
    echo "Experiment:  $EXP_NAME"
    echo "Log file:    $LOG_FILE"
    echo "Done marker: $DONE_FILE"
    exit 0
fi

# Prevent two copies of this updated launcher from training the same setting.
exec 9>"$LOCK_FILE"
if ! flock -n 9; then
    echo "SKIPPED: another updated job is already running this experiment."
    echo "Experiment: $EXP_NAME"
    echo "Lock file:  $LOCK_FILE"
    exit 0
fi

if [ ! -f "$TRAIN_SCRIPT" ]; then
    echo "Training script not found: $TRAIN_SCRIPT" >&2
    exit 2
fi

if [ ! -d "$FEATURES_FOLDER" ]; then
    echo "Feature folder not found: $FEATURES_FOLDER" >&2
    exit 2
fi

# The simulation launcher uses --no-consolidate, so the expected source is
# normally MASTER_SHARD_DIR. The training code also supports an aggregate file.
if [ -d "$MASTER_SHARD_DIR" ]; then
    MASTER_SOURCE_TYPE="assignment shards"
    MASTER_SOURCE_PATH="$MASTER_SHARD_DIR"
elif [ -f "$MASTER_FILE" ]; then
    MASTER_SOURCE_TYPE="aggregate pickle"
    MASTER_SOURCE_PATH="$MASTER_FILE"
else
    echo "Neither the master shard directory nor aggregate pickle was found:" >&2
    echo "Shard directory: $MASTER_SHARD_DIR" >&2
    echo "Aggregate file:  $MASTER_FILE" >&2
    exit 2
fi

if [ "$SAVE_TEST_MANIFEST" = "True" ] && [ ! -d "$CASCADE_SHARD_DIR" ]; then
    echo "Cascade shard directory not found:" >&2
    echo "$CASCADE_SHARD_DIR" >&2
    echo "Check FEATURE_TAG and confirm that the cascade-enabled simulation finished." >&2
    exit 2
fi

FEATURE_SHARD_COUNT=0
CASCADE_SHARD_COUNT=0
if [ -d "$MASTER_SHARD_DIR" ]; then
    FEATURE_SHARD_COUNT=$(find "$MASTER_SHARD_DIR" -maxdepth 1 -type f -name 'assignment_*_features.pkl' | wc -l)
fi
if [ -d "$CASCADE_SHARD_DIR" ]; then
    CASCADE_SHARD_COUNT=$(find "$CASCADE_SHARD_DIR" -maxdepth 1 -type f -name 'assignment_*_cascades.npz' | wc -l)
fi

if [ -d "$MASTER_SHARD_DIR" ] && [ "$FEATURE_SHARD_COUNT" -lt "$MASTER_ASSIGNMENTS" ]; then
    echo "Incomplete feature master: found $FEATURE_SHARD_COUNT of $MASTER_ASSIGNMENTS shards." >&2
    exit 2
fi
if [ "$SAVE_TEST_MANIFEST" = "True" ] && [ "$CASCADE_SHARD_COUNT" -lt "$MASTER_ASSIGNMENTS" ]; then
    echo "Incomplete cascade master: found $CASCADE_SHARD_COUNT of $MASTER_ASSIGNMENTS shards." >&2
    exit 2
fi

echo "$RUN_HEADER"
echo "SLURM job ID:               ${SLURM_JOB_ID:-unknown}"
echo "Array task ID:              ${SLURM_ARRAY_TASK_ID:-unknown}"
echo "Dataset index:              $DATASET_INDEX"
echo "Dataset tag:                $DATASET_TAG"
echo "Experiment:                 $EXP_NAME"
echo "Graph label:                $GRAPH_LABEL"
echo "Graph name:                 $GRAPH_NAME"
echo "Node-count argument:        $NODE_COUNT"
echo "Connections per node:       $CPN"
echo "Master assignments:         $MASTER_ASSIGNMENTS"
echo "Selected assignments:       $VALUE"
echo "Nested assignment seed:     $SUBSET_SEED"
echo "Features per assignment:    $FEATURES_PER_ASSIGNMENT"
echo "Cascades per seed:          $NUM_CASCADES"
echo "Seed percentage:            $SEED_PERCENTAGE"
echo "Feature mode:               $FEATURE_MODE"
echo "Available feature columns:  $AVAILABLE_FEATURE_DIMENSION"
echo "Model input feature columns:$INPUT_FEATURE_COUNT"
echo "Noise setting:              $P_SETTING"
echo "p1:                         $P1"
echo "p2:                         $P2"
echo "q:                          $Q_VAL"
echo "Feature directory:          $FEATURES_FOLDER"
echo "Master source type:         $MASTER_SOURCE_TYPE"
echo "Master source path:         $MASTER_SOURCE_PATH"
echo "Feature shard count:        $FEATURE_SHARD_COUNT"
echo "Cascade shard count:        $CASCADE_SHARD_COUNT"
echo "Model:                      $MODEL_NAME"
echo "Normalization:              True"
echo "Runs:                       $K_RUNS"
echo "Epochs:                     $NUM_EPOCHS"
echo "Learning rate:              $LEARNING_RATE"
echo "Weight decay:               $WEIGHT_DECAY"
echo "Patience:                   $PATIENCE"
echo "Minimum epochs:             $MIN_EPOCHS"
echo "Uncertainty:                $COMPUTE_UNCERTAINTY"
echo "Uncertainty confidence:     $UNCERTAINTY_CONFIDENCE"
echo "Save uncertainty JSON:      $SAVE_UNCERTAINTY_RESULTS"
echo "Save combined test IDs:     $SAVE_TEST_MANIFEST"
echo "Test manifest:              $TEST_MANIFEST_FILE"
echo "Cascade shard directory:    $CASCADE_SHARD_DIR"
echo "Verify cascade shards:      $VERIFY_CASCADE_SHARDS"
echo "Log file:                   $LOG_FILE"
echo "Done marker:                $DONE_FILE"
echo "================================================================"

"$PYTHON" -u -s "$TRAIN_SCRIPT" \
    --name="$EXP_NAME" \
    --number_of_assignments="$VALUE" \
    --source_number_of_assignments="$MASTER_ASSIGNMENTS" \
    --subset_seed="$SUBSET_SEED" \
    --features_per_assignment="$FEATURES_PER_ASSIGNMENT" \
    --num_cascades="$NUM_CASCADES" \
    --alpha="$ALPHA" \
    --node_count="$NODE_COUNT" \
    --model_name="$MODEL_NAME" \
    --graph_name="$GRAPH_NAME" \
    --connections_per_node="$CPN" \
    --assignemnt_generator_type="$FEATURE_MODE" \
    --seed_percentage="$SEED_PERCENTAGE" \
    --features_folder="$FEATURES_FOLDER" \
    --graph_folder="$GRAPH_FOLDER" \
    --p1="$P1" \
    --p2="$P2" \
    --q_val="$Q_VAL" \
    --development_fraction=0.80 \
    --unseen_validation_fraction=0.10 \
    --seen_validation_fraction=0.10 \
    --seen_test_fraction=0.00 \
    --seen_validation_weight=0.80 \
    --normalize_features=True \
    --input_feature_count="$INPUT_FEATURE_COUNT" \
    --compute_uncertainty="$COMPUTE_UNCERTAINTY" \
    --uncertainty_confidence="$UNCERTAINTY_CONFIDENCE" \
    --save_uncertainty_results="$SAVE_UNCERTAINTY_RESULTS" \
    --uncertainty_results_folder="$UNCERTAINTY_RESULTS_DIR" \
    --save_test_manifest="$SAVE_TEST_MANIFEST" \
    --test_manifest_folder="$TEST_MANIFEST_DIR" \
    --cascade_shard_folder="$CASCADE_SHARD_DIR" \
    --verify_cascade_shards="$VERIFY_CASCADE_SHARDS" \
    --split_seed="$SPLIT_SEED" \
    --batch_size="$BATCH_SIZE" \
    --k_runs="$K_RUNS" \
    --lr="$LEARNING_RATE" \
    --weight_decay="$WEIGHT_DECAY" \
    --patience="$PATIENCE" \
    --min_epochs="$MIN_EPOCHS" \
    --num_epochs="$NUM_EPOCHS" \
    --device=cuda:0

echo "================================================================"
echo "Finished:    $EXP_NAME"
echo "Metrics log: $LOG_FILE"
echo "================================================================"

write_done_marker "successful_current_run"
echo "Completion marker written: $DONE_FILE"
